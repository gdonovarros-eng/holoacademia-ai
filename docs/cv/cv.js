function createContactDetail(item) {
  const article = createNode("article", "contact-detail");
  const icon = createIcon(item.icon);
  if (icon) article.append(icon);
  article.append(createNode("span", "", item.label));

  if (item.href) {
    const anchor = createNode("a", "", item.value);
    anchor.href = item.href;
    article.append(anchor);
  } else {
    article.append(createNode("p", "", item.value));
  }

  return article;
}

function populateList(id, items, factory) {
  const container = document.getElementById(id);
  if (!container) return;
  items.forEach((item) => container.append(factory(item)));
}

