function createKpiCard(item) {
  const article = createNode("article", "kpi-card");
  const value = createNode("strong", "");
  const counter = createNode("span", "counter");

  counter.dataset.value = String(item.value);
  counter.dataset.decimals = String(item.decimals || 0);
  counter.dataset.prefix = item.prefix || "";
  counter.dataset.suffix = item.suffix || "";
  counter.textContent = `${item.prefix || ""}0${item.suffix || ""}`;

  const icon = createIcon(item.icon);
  if (icon) article.append(icon);
  value.append(counter);
  article.append(value);
  article.append(createNode("h3", "", item.title));
  article.append(createNode("p", "", item.detail));
  return article;
}

